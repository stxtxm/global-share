/**
 * Renvoie une traduction pour la langue demandée, avec repli sur le français.
 * `{name}` est remplacé par `params.name` quand la clé comporte un espace réservé.
 */
export function translate(
  language: string,
  key: string,
  params?: Record<string, string | number>
): string {
  const lang = (language in translations ? language : 'fr') as SettingsLanguage;
  let value = translations[lang][key] ?? translations.fr[key] ?? key;
  if (params) {
    for (const [param, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${param}}`, String(replacement));
    }
  }
  return value;
}

